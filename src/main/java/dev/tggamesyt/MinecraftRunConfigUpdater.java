package dev.tggamesyt;

import com.intellij.execution.RunManager;
import com.intellij.execution.RunnerAndConfigurationSettings;
import com.intellij.execution.configurations.RunConfiguration;
import com.intellij.openapi.externalSystem.model.execution.ExternalSystemTaskExecutionSettings;
import com.intellij.openapi.project.Project;

import java.lang.reflect.Method;
import java.util.regex.Pattern;

public class MinecraftRunConfigUpdater {

    private static final Pattern MC_ARGS_PATTERN = Pattern.compile(
            "(--username\\s+\\S+)|" +
                    "(--uuid\\s+\\S+)|" +
                    "(--accessToken\\s+\\S+)|" +
                    "(--userType\\s+\\S+)"
    );

    // Any previously-injected "--args=..." block that carries our login flags, so re-running stays
    // idempotent instead of stacking duplicate --args onto a Gradle run configuration.
    private static final Pattern GRADLE_ARGS_PATTERN = Pattern.compile(
            "--args=([\"'])(?:(?!\\1).)*?(?:--username|--accessToken)(?:(?!\\1).)*?\\1"
    );

    private static String configName = "Minecraft Client";

    // Guards against infinite recursion: makeStable() fires runConfigurationChanged, which our
    // RunManagerListener handles by calling updateArgs() again. Without this flag that would loop
    // until a StackOverflowError froze the IDE.
    private static volatile boolean updating = false;

    public static void setConfigName(String name) {
        configName = name;
    }

    public static String getConfigName() {
        return configName;
    }

    /**
     * True for run configurations that launch the Minecraft client. Covers the Fabric/Loom
     * "Minecraft Client" config (the configurable default name) as well as the Forge/NeoForge
     * configs generated by Minecraft Dev, whose names end in {@code runClient}.
     */
    public static boolean isClientConfigName(String name) {
        if (name == null) return false;
        return configName.equals(name) || name.endsWith("runClient");
    }

    /** The currently selected account, defaulting to the first one if nothing is selected yet. */
    public static MinecraftAccount selectedAccount() {
        MinecraftAccountsState state = MinecraftAccountsState.getInstance();
        if (state.accounts.isEmpty()) return null;
        if (state.selectedAccountId == null
                || state.accounts.stream().noneMatch(a -> a.id.equals(state.selectedAccountId))) {
            state.selectedAccountId = state.accounts.get(0).id;
        }
        return state.accounts.stream()
                .filter(a -> a.id.equals(state.selectedAccountId))
                .findFirst()
                .orElse(null);
    }

    /**
     * Writes the currently selected account into every Minecraft client run configuration.
     *
     * <p>Two configuration shapes are supported, because the Minecraft Dev plugin generates
     * different types depending on platform and version:
     * <ul>
     *   <li><b>{@code ApplicationConfiguration}</b> (Forge/NeoForge, and older Loom) — the login
     *       flags go into the config's program parameters.</li>
     *   <li><b>{@code GradleRunConfiguration}</b> (current Fabric/Loom) — this type has no program
     *       parameters; the flags are passed to the Gradle {@code runClient} task through its
     *       {@code --args="…"} script parameter instead. This is the case that silently did nothing
     *       before, so the account never applied on the newest Minecraft Dev + Minecraft versions.</li>
     * </ul>
     */
    public static void updateArgs() {
        // Keep the global Gradle init-script args file current (no-op unless the user enabled it).
        MinecraftGradleInitScript.refresh();

        Project project = MinecraftOAuthConfigurable.project;
        if (project == null) return;
        if (updating) return; // re-entered via makeStable() -> runConfigurationChanged; skip
        updating = true;

        try {
            MinecraftAccount acc = selectedAccount();
            if (acc == null) return;

            RunManager runManager = RunManager.getInstance(project);
            boolean found = false;

            for (RunnerAndConfigurationSettings settings : runManager.getAllSettings()) {
                RunConfiguration config = settings.getConfiguration();
                if (!isClientConfigName(config.getName())) continue;

                found = true;
                boolean applied = applyProgramParameters(config, acc);
                if (!applied) {
                    applied = applyGradleArgs(config, acc);
                }
                if (applied) {
                    // Tell RunManager to persist the change
                    runManager.makeStable(settings);
                }
            }

            if (!found) {
                System.err.println("No Minecraft client run configuration found to update.");
            }

        } catch (Exception e) {
            e.printStackTrace();
        } finally {
            updating = false;
        }
    }

    /**
     * Program-parameters path ({@code ApplicationConfiguration} and friends). Returns true if the
     * config exposes {@code setProgramParameters} and we wrote to it.
     */
    private static boolean applyProgramParameters(RunConfiguration config, MinecraftAccount acc) throws Exception {
        Method setter = findMethod(config.getClass(), "setProgramParameters", String.class);
        if (setter == null) return false;

        String args = "";
        Method getter = findMethod(config.getClass(), "getProgramParameters");
        if (getter != null) {
            getter.setAccessible(true);
            Object result = getter.invoke(config);
            if (result instanceof String) {
                args = (String) result;
            }
        }

        // Remove any login flags we (or a previous run) added, then append the current account's.
        args = MC_ARGS_PATTERN.matcher(args).replaceAll("").trim();
        args = (args + " " + loginArgs(acc)).trim();

        setter.setAccessible(true);
        setter.invoke(config, args);
        return true;
    }

    /**
     * Gradle path ({@code GradleRunConfiguration} / {@code ExternalSystemRunConfiguration}). The
     * login flags are passed through the run task's {@code --args="…"} script parameter. Returns
     * true if the config exposes external-system settings and we wrote to them.
     */
    private static boolean applyGradleArgs(RunConfiguration config, MinecraftAccount acc) throws Exception {
        Method getSettings = findMethod(config.getClass(), "getSettings");
        if (getSettings == null) return false;
        getSettings.setAccessible(true);
        Object raw = getSettings.invoke(config);
        if (!(raw instanceof ExternalSystemTaskExecutionSettings)) return false;

        ExternalSystemTaskExecutionSettings settings = (ExternalSystemTaskExecutionSettings) raw;
        String params = settings.getScriptParameters();
        if (params == null) params = "";

        // Drop our previously-injected --args block so repeated runs don't accumulate duplicates.
        params = GRADLE_ARGS_PATTERN.matcher(params).replaceAll("").trim();
        params = (params + " --args=\"" + loginArgs(acc) + "\"").trim();

        settings.setScriptParameters(params);
        return true;
    }

    /** The login program arguments for an account (premium carries uuid/token, cracked is name-only). */
    private static String loginArgs(MinecraftAccount acc) {
        if (acc.type == MinecraftAccount.Type.CRACKED) {
            return "--username " + acc.username;
        }
        // Use the stored token even if marked expired; a background refresh will update it shortly.
        return "--username " + acc.username
                + " --uuid " + acc.uuid
                + " --accessToken " + acc.accessToken
                + " --userType msa";
    }

    /** Finds a Minecraft client run configuration's settings, or null if none exists yet. */
    public static RunnerAndConfigurationSettings findClientSettings(Project project) {
        if (project == null) return null;
        for (RunnerAndConfigurationSettings settings : RunManager.getInstance(project).getAllSettings()) {
            if (isClientConfigName(settings.getConfiguration().getName())) {
                return settings;
            }
        }
        return null;
    }

    /** Walks the class hierarchy to find a method by name and parameter types. */
    private static Method findMethod(Class<?> clazz, String name, Class<?>... paramTypes) {
        while (clazz != null) {
            try {
                return clazz.getDeclaredMethod(name, paramTypes);
            } catch (NoSuchMethodException e) {
                for (Class<?> iface : clazz.getInterfaces()) {
                    try {
                        return iface.getDeclaredMethod(name, paramTypes);
                    } catch (NoSuchMethodException ignored) {}
                }
                clazz = clazz.getSuperclass();
            }
        }
        return null;
    }
}
