package dev.tggamesyt;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.attribute.PosixFilePermission;
import java.util.EnumSet;
import java.util.Set;

/**
 * Global Gradle integration for the {@link MinecraftArgs#PLACEHOLDER} token.
 *
 * <p>A raw {@code ./gradlew runClient --args="--minecraftArgsHere"} typed in a terminal can't be
 * intercepted from inside the IDE, so to support it (and all Gradle runs) this installs a Gradle
 * init script into the Gradle user home ({@code $GRADLE_USER_HOME/init.d/}, default {@code ~/.gradle}).
 * The init script, at task-execution time, replaces the {@code --minecraftArgsHere} token in any
 * task's {@code args} with the login arguments this plugin writes to a sibling file.
 *
 * <p>The login args (including the Microsoft access token) are written to
 * {@code $GRADLE_USER_HOME/mcdev-premlogin/args.txt} with owner-only permissions where the OS
 * supports it. This is opt-in: nothing is written unless the user enables it in settings.
 */
public final class MinecraftGradleInitScript {

    private static final String INIT_SCRIPT_NAME = "mcdev-premlogin.init.gradle";
    private static final String DATA_DIR = "mcdev-premlogin";
    private static final String ARGS_FILE_NAME = "args.txt";

    private MinecraftGradleInitScript() {}

    /** Resolves the Gradle user home: {@code $GRADLE_USER_HOME} if set, otherwise {@code ~/.gradle}. */
    private static Path gradleUserHome() {
        String env = System.getenv("GRADLE_USER_HOME");
        if (env != null && !env.isBlank()) {
            return Paths.get(env);
        }
        return Paths.get(System.getProperty("user.home"), ".gradle");
    }

    private static Path initScriptPath() {
        return gradleUserHome().resolve("init.d").resolve(INIT_SCRIPT_NAME);
    }

    private static Path argsFilePath() {
        return gradleUserHome().resolve(DATA_DIR).resolve(ARGS_FILE_NAME);
    }

    public static boolean isEnabled() {
        return MinecraftAccountsState.getInstance().gradleInitScriptEnabled;
    }

    /**
     * Installs the init script and writes the current account's args. Persists the enabled flag.
     * Returns true on success.
     */
    public static boolean enable() {
        try {
            Path initScript = initScriptPath();
            Files.createDirectories(initScript.getParent());
            Files.write(initScript, initScriptContents().getBytes(StandardCharsets.UTF_8));
            MinecraftAccountsState.getInstance().gradleInitScriptEnabled = true;
            refresh();
            return true;
        } catch (IOException e) {
            e.printStackTrace();
            return false;
        }
    }

    /** Removes the init script and the args file, and clears the enabled flag. */
    public static void disable() {
        MinecraftAccountsState.getInstance().gradleInitScriptEnabled = false;
        try {
            Files.deleteIfExists(initScriptPath());
        } catch (IOException ignored) {
        }
        try {
            Files.deleteIfExists(argsFilePath());
        } catch (IOException ignored) {
        }
    }

    /** Rewrites the args file with the currently selected account's login args, if enabled. */
    public static void refresh() {
        if (!isEnabled()) return;
        String args = MinecraftArgs.forSelectedAccount();
        try {
            Path argsFile = argsFilePath();
            Files.createDirectories(argsFile.getParent());
            Files.write(argsFile, args.getBytes(StandardCharsets.UTF_8));
            restrictToOwner(argsFile);
        } catch (IOException e) {
            e.printStackTrace();
        }
    }

    /** Best-effort owner-only (0600) permissions on POSIX file systems. */
    private static void restrictToOwner(Path file) {
        try {
            Set<PosixFilePermission> perms = EnumSet.of(
                    PosixFilePermission.OWNER_READ, PosixFilePermission.OWNER_WRITE);
            Files.setPosixFilePermissions(file, perms);
        } catch (UnsupportedOperationException | IOException ignored) {
            // Non-POSIX (e.g. Windows): rely on the default user-profile ACLs.
        }
    }

    /**
     * The Gradle init script. At task-graph time it attaches a {@code doFirst} to every task that
     * carries an {@code args} list containing the placeholder, and at execution time swaps the
     * placeholder for the tokens read fresh from the args file (so a refreshed token is picked up).
     */
    private static String initScriptContents() {
        return "// Generated by the Minecraft OAuth IntelliJ plugin (mcdev-premlogin).\n"
                + "// Expands the \"" + MinecraftArgs.PLACEHOLDER + "\" placeholder in Gradle run tasks.\n"
                + "// Delete this file (or disable it in the plugin settings) to remove it.\n"
                + "def mcdevArgsFile = new File(gradle.gradleUserHomeDir, '" + DATA_DIR + "/" + ARGS_FILE_NAME + "')\n"
                + "def mcdevPlaceholder = '" + MinecraftArgs.PLACEHOLDER + "'\n"
                + "gradle.taskGraph.whenReady { graph ->\n"
                + "    graph.allTasks.each { task ->\n"
                + "        try {\n"
                + "            if (task.hasProperty('args') && (task.args instanceof List)\n"
                + "                    && (task.args as List).contains(mcdevPlaceholder)) {\n"
                + "                task.doFirst {\n"
                + "                    def repl = mcdevArgsFile.isFile() ? mcdevArgsFile.text.trim() : ''\n"
                + "                    def toks = repl.isEmpty() ? [] : (repl.split(/\\s+/) as List)\n"
                + "                    def out = []\n"
                + "                    (task.args as List).each { a ->\n"
                + "                        if (a == mcdevPlaceholder) { out.addAll(toks) } else { out << a }\n"
                + "                    }\n"
                + "                    task.args = out\n"
                + "                }\n"
                + "            }\n"
                + "        } catch (ignored) { }\n"
                + "    }\n"
                + "}\n";
    }
}
